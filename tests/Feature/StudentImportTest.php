    public function test_full_import_creates_correct_db_records()
    {
        $admin = User::factory()->create();
        $admin->assignRole('SUPER_ADMIN');

        $nisn = '0118926088';
        $nis = '131232040009260001';

        $file = $this->singleSheetFile('XII IPA', [
            [1, $nisn, $nis, 'ADZIKRA KHANSA HAURA', 'P'],
        ]);

        $response = $this->actingAs($admin)->post('/api/members/import', ['file' => $file]);
        $response->assertOk();

        // Check User
        $user = User::where('username', $nisn)->first();
        $this->assertNotNull($user);
        $this->assertEquals($nisn, $user->username);
        $this->assertNull($user->email);
        $this->assertTrue(Hash::check($nisn, $user->password));
        $this->assertTrue((bool) $user->must_change_password);
        $this->assertTrue($user->hasRole('MEMBER'));

        // Check Member
        $member = Member::where('identity_number', $nisn)->first();
        $this->assertNotNull($member);
        $this->assertEquals($nis, $member->member_number);
        $this->assertEquals('ADZIKRA KHANSA HAURA', $member->name);
        $this->assertEquals($user->id, $member->user_id);
        $this->assertEquals('ACTIVE', $member->status);
        $this->assertNull($member->date_of_birth);

        // Check class/major
        $classLevel = ClassLevel::find($member->class_level_id);
        $this->assertEquals('XII', $classLevel->code);

        $major = Major::find($member->major_id);
        $this->assertEquals('IPA', $major->code);
    }

