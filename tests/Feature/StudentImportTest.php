            ]],
        ]);

        $response = $this->actingAs($admin)
            ->post('/api/members/import/preview', [
                'file' => $file,
            ]);

        $response->assertOk();

        $this->assertSame(3, count($response->json('data.sheets')));
        $this->assertSame(3, $response->json('data.total'));
        $this->assertSame(3, $response->json('data.valid'));
