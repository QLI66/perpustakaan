    private function buildWorkbook(array $sheets, string $filename = 'import.xlsx'): UploadedFile
    {
        $path = storage_path("app/test_{$filename}");
        $options = new XlsxWriterOptions;
        $writer = new XlsxWriter($options);
        $writer->openToFile($path);

        foreach ($sheets as $i => $sheetDef) {
            if ($i === 0) {
                $writer->getCurrentSheet()->setName($sheetDef['name']);
            } else {
                $sheet = $writer->addNewSheetAndMakeItCurrent();
                $sheet->setName($sheetDef['name']);
            }

            // Title rows (decoration before the real header)
            foreach ($sheetDef['titleRows'] ?? [] as $titleRow) {
                $cells = array_map(fn ($v) => Cell::fromValue($v), $titleRow);
                $writer->addRow(new Row($cells));
            }

            // Real header row
            $headers = $sheetDef['headers'] ?? ['NO', 'NISN', 'NIS', 'NAMA', 'JK'];
            $cells = array_map(fn ($v) => Cell::fromValue($v), $headers);
            $writer->addRow(new Row($cells));

            // Data rows
            foreach ($sheetDef['rows'] as $dataRow) {
                $cells = array_map(fn ($v) => Cell::fromValue($v), $dataRow);
                $writer->addRow(new Row($cells));
            }
        }

        $writer->close();

        return new UploadedFile(
            $path,
            $filename,
            'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
            null,
            true
        );
    }

    /** Single-sheet helper with real format */
    private function singleSheetFile(
        string $sheetName,
        array $rows,
        array $titleRows = []
    ): UploadedFile {
        return $this->buildWorkbook([
            [
                'name' => $sheetName,
                'titleRows' => $titleRows,
                'rows' => $rows,
            ],
        ]);
    }

