        $third = collect($response->json('data.rows'))
            ->firstWhere('sheet', 'X C');

        $this->assertNotNull($third);
        $this->assertSame('X', $third['class']);
        $this->assertNull($third['major']);
        $this->assertSame(1, $third['student_number']);
    }

    public function test_student_number_resets_for_each_sheet(): void
    {
        $admin = User::factory()->create();
        $admin->assignRole('SUPER_ADMIN');

        $file = $this->buildWorkbook([
            ['name' => 'X A', 'rows' => [
                [1, '0112000011', 'NIS-XA-011', 'SISWA SATU', 'L'],
                [2, '0112000012', 'NIS-XA-012', 'SISWA DUA', 'P'],
            ]],
            ['name' => 'X B', 'rows' => [
                [1, '0112000021', 'NIS-XB-021', 'SISWA TIGA', 'L'],
            ]],
        ]);

        $response = $this->actingAs($admin)
            ->post('/api/members/import/preview', [
                'file' => $file,
            ]);

        $response->assertOk();

        $rows = collect($response->json('data.rows'));

        $xa = $rows->where('sheet', 'X A')
            ->values();

        $xb = $rows->where('sheet', 'X B')
            ->values();

        $this->assertSame(1, $xa[0]['student_number']);
        $this->assertSame(2, $xa[1]['student_number']);
        $this->assertSame(1, $xb[0]['student_number']);
    }

